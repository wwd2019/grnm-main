options(error=function() {traceback(15); quit(status=1)})
root <- Sys.getenv('PANDO_DATADIR','/home/wwd/py_code/mhr/final')
out <- file.path(root,'new_grn','audit')
dir.create(out,recursive=TRUE,showWarnings=FALSE)
sink(file.path(out,'inputs.txt'),split=TRUE)
cat('INPUT AUDIT; no expression transfer or model fitting\n')
packages <- c('Seurat','Signac','Pando','GenomicRanges','BSgenome.Hsapiens.UCSC.hg38','EnsDb.Hsapiens.v86','reticulate','igraph')
for(p in packages) cat(p,if(requireNamespace(p,quietly=TRUE)) as.character(packageVersion(p)) else 'MISSING','\n')
suppressPackageStartupMessages(library(Seurat))
suppressPackageStartupMessages(library(Signac))
cells <- list()
for (f in c('ATAC_all_merged_srt.rds','RNA_all_merged_srt.rds','lines12_RNATAC16_26_integrated_v3scores_srt.rds')) {
  cat('\nFILE',f,'\n'); flush.console()
  x <- readRDS(file.path(root,f))
  cat('class',class(x),'dim',dim(x),'\n')
  cat('assays',names(x@assays),'\n')
  cat('metadata',colnames(x[[]]),'\n')
  cat('reductions',names(x@reductions),'\n')
  for(a in names(x@assays)) {cat('assay',a,'class',class(x[[a]]),'dim',dim(x[[a]]),'\n'); if(inherits(x[[a]],'Assay5')) cat('layers',Layers(x[[a]]),'\n')}
  write.csv(head(x[[]],30),file.path(out,paste0(f,'.metadata_head.csv')))
  saveRDS(x[[]],file.path(out,paste0(f,'.metadata.rds')))
  cells[[f]] <- colnames(x)
  if('ATAC'%in%names(x@assays)) print(GenomeInfoDb::seqinfo(x[['ATAC']]))
  cat('commands',names(x@commands),'\n')
  rm(x); gc()
}
cat('\nRNA/ATAC shared barcodes',length(intersect(cells[[1]],cells[[2]])),'\n')
saveRDS(cells,file.path(out,'cell_names.rds'))
ann <- readRDS(file.path(root,'final_geneGr.rds'))
print(ann); print(GenomeInfoDb::seqinfo(ann))
print(sessionInfo())
